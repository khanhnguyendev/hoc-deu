-- §4.7: the engine rules version (lib/domain/rules.ts RULES_VERSION). M4 bumps both together.
create or replace function public.rules_version() returns integer
language sql immutable set search_path = '' as $$
  select 1
$$;

-- §4.4: the types a learner may write (lib/domain/events.ts LEARNER_EVENT_TYPES).
create or replace function public.learner_event_types() returns text[]
language sql immutable set search_path = '' as $$
  select array[
    'block.checked_in',
    'item.result',
    'lesson.completed',
    'exercise.submitted',
    'prompt.completed',
    'item.skipped',
    'item.readded',
    'track.enrolled',
    'track.updated',
    'track.paused',
    'track.resumed',
    'track.removed',
    'track.reset',
    'schedule.changed',
    'settings.changed'
  ]::text[]
$$;

-- §5.1: the date part of (the wall-clock time of p_at in p_timezone, minus the day start).
-- [RF-1] 020-local-day-parity (generated by `pnpm db:fixtures`) checks it against TypeScript
-- localDay on the shared fixtures.
create or replace function public.local_day(
  p_at timestamptz, p_timezone text, p_day_starts_at time
) returns date
language sql stable set search_path = '' as $$
  select ((p_at at time zone p_timezone) - (p_day_starts_at - time '00:00'))::date
$$;

-- §4.1: the schedule version in force at p_at is the latest with effective_at <= p_at; without
-- one, the default schedule (Asia/Ho_Chi_Minh, 04:00 — decision 5). Security invoker: a learner
-- only sees their own versions (RLS), so for anyone else it answers with the default.
-- plpgsql, not sql: Postgres 17 keeps a SQL function's plan for the rest of the transaction
-- wherever the caller keeps its expression state (the events trigger does), RLS filter included,
-- even after the role changes. A learner insert followed by a system insert for another user in
-- the same transaction then saw no versions. plpgsql plans live in the plan cache, which re-plans
-- when the role changes (030-events, section 2).
create or replace function public.user_local_day(p_user_id uuid, p_at timestamptz) returns date
language plpgsql stable set search_path = '' as $$
begin
  return coalesce(
    (
      select public.local_day(p_at, s.timezone, s.day_starts_at)
      from public.schedule_versions s
      where s.user_id = p_user_id and s.effective_at <= p_at
      order by s.effective_at desc
      limit 1
    ),
    public.local_day(p_at, 'Asia/Ho_Chi_Minh', time '04:00')
  );
end $$;

